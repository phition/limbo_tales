/**
 * 용병의 성향(trait)과 클래스 역할(role)을 바탕으로 공성/수성 전술을 도출하는 헬퍼 함수
 */
export function resolveSiegeTactic(trait?: string, role?: CharacterClassRole): SiegeTacticDefinition {
  const safeRole: CharacterClassRole = role || 'tank';
  const safeTrait = trait && ALL_HERO_TRAITS.includes(trait as any) ? trait : '균형잡힌 정예';

  const key = `${safeRole}_${safeTrait}`;
  if (SIEGE_TACTICS_REGISTRY[key]) {
    return SIEGE_TACTICS_REGISTRY[key];
  }

  // 폴백 기본 전술
  return SIEGE_TACTICS_REGISTRY[`${safeRole}_균형잡힌 정예`] || SIEGE_TACTICS_REGISTRY['tank_균형잡힌 정예'];
}
